package com.sa.core;

public class AccesoNoPermitidoException extends Exception {

	/**
	 * 
	 */
	private static final long serialVersionUID = 1L;

	public AccesoNoPermitidoException() {
		super();
	}

	public AccesoNoPermitidoException(String msg) {
		super(msg);
	}

	public AccesoNoPermitidoException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

	public AccesoNoPermitidoException(Throwable arg0) {
		super(arg0);
	}

}
